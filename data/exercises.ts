// ---------------------------------------------------------------------------
// Movement Vault — data model and mock dataset.
//
// ~70 exercises across Push, Pull, Legs, Core, and Skills. Every exercise
// carries a `movementPattern` (the functional pattern it trains — distinct
// from `category`, which is a broader grouping) and `cues` (short coaching
// phrases, distinct from the numbered `instructions`).
//
// Progression chains are intentionally real and occasionally cross
// categories — e.g. Elevated Pike Push-Up (Push) leads to Wall Handstand
// Push-Up (Skills), because that's how the skill actually develops. Not
// every exercise sits on a chain; standalone accessory movements
// (Russian Twist, Bear Crawl, Step-Up) are common in a real vault too.
// ---------------------------------------------------------------------------

